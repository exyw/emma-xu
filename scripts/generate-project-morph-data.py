"""Sample the supplied outlined SVG glyphs for the Projects transition.

This writes only a small coordinate field. The page still renders the original SVGs.
Run from the repository root when the artwork or overview slots change.
"""

from pathlib import Path
from xml.etree import ElementTree
import json
import re

ROOT = Path(__file__).resolve().parents[1]
ASCII = ROOT / "assets/projects/ascii"
config_text = (ROOT / "projects-config.js").read_text()
config_match = re.search(r"window\.projectConfig\s*=\s*(\{.*\});\s*$", config_text, re.S)
if not config_match:
    raise ValueError("projects-config.js must contain a JSON object assignment")
CONFIG = json.loads(config_match.group(1))
CROP = tuple(CONFIG["crop"][name] for name in ("x", "y", "width", "height"))
SLOTS = {
    item["id"]: tuple(item["slot"][name] for name in ("x", "y", "width", "height")) + (item["small"],)
    for item in CONFIG["projects"]
}
TARGETS = {
    item["id"]: (item["large"], item["art"]["maxWidth"], item["art"]["maxHeight"])
    for item in CONFIG["projects"]
}
MOVE = re.compile(r"M\s*(-?\d+(?:\.\d+)?)\s*[, ]\s*(-?\d+(?:\.\d+)?)")


def svg_points(path):
    root = ElementTree.parse(path).getroot()
    view_box = tuple(float(value) for value in root.get("viewBox").split())
    points = []
    for element in root.iter():
        if element.tag.rsplit("}", 1)[-1] != "path":
            continue
        points.extend((float(x), float(y)) for x, y in MOVE.findall(element.get("d", "")))
    return view_box, points


def spaced(points, display_width, display_height, limit=2600):
    # One source per roughly 4px cell avoids repeated path subcontours.
    cells = {}
    for x, y in points:
        if 0 <= x <= 1 and 0 <= y <= 1:
            cells.setdefault((int(x * display_width / 4), int(y * display_height / 4)), (x, y))
    ordered = sorted(cells.values(), key=lambda point: (point[1], point[0]))
    if len(ordered) > limit:
        ordered = [ordered[int(i * len(ordered) / limit)] for i in range(limit)]
    return [[round(x * 10000), round(y * 10000)] for x, y in ordered]


def source_points():
    crop_x, crop_y, crop_w, crop_h = CROP
    _, silhouette = svg_points(ASCII / "Silhouette ASCII.svg")
    points = [((x - crop_x) / crop_w, (y - crop_y) / crop_h) for x, y in silhouette]
    for x, y, width, height, filename in SLOTS.values():
        (vx, vy, vw, vh), icon = svg_points(ASCII / filename)
        points.extend(
            ((x + (px - vx) / vw * width - crop_x) / crop_w,
             (y + (py - vy) / vh * height - crop_y) / crop_h)
            for px, py in icon
        )
    return spaced(points, 760 * crop_w / crop_h, 760)


def target_points(filename, max_width, max_height):
    (vx, vy, vw, vh), points = svg_points(ASCII / filename)
    scale = min(max_width / vw, max_height / vh)
    return spaced([((x - vx) / vw, (y - vy) / vh) for x, y in points], vw * scale, vh * scale)


output = {"source": source_points()}
for key, (filename, width, height) in TARGETS.items():
    output[key] = target_points(filename, width, height)

destination = ROOT / "projects-morph-data.js"
destination.write_text("// Generated by scripts/generate-project-morph-data.py.\n"
                       "window.projectMorphPoints = " + json.dumps(output, separators=(",", ":")) + ";\n")
for key, values in output.items():
    print(key, len(values))
