"""Commit the silhouette's individual SVG paths for its Home entrance.

The supplied silhouette has one path per ASCII character. Keeping those paths
separate lets the entrance move characters and then hand off to the unchanged
overview SVG without a raster or a second set of glyphs at rest.
"""

import json
import re
from pathlib import Path
from xml.etree import ElementTree


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/projects/ascii/Silhouette ASCII.svg"
DESTINATION = ROOT / "projects-entry-data.js"
MOVE = re.compile(r"^M\s*(-?\d+(?:\.\d+)?)\s*[, ]\s*(-?\d+(?:\.\d+)?)")

glyphs = []
for path in ElementTree.parse(SOURCE).getroot():
    if path.tag.rsplit("}", 1)[-1] != "path":
        continue
    data = path.get("d", "")
    match = MOVE.match(data)
    if not match:
        raise ValueError("Each silhouette glyph must start with an absolute move")
    glyphs.append([float(match[1]), float(match[2]), data])

DESTINATION.write_text(
    "// Generated by scripts/generate-project-entry-data.py.\n"
    "window.projectEntryGlyphs = " + json.dumps(glyphs, separators=(",", ":")) + ";\n"
)
print(f"Wrote {len(glyphs)} silhouette glyphs to {DESTINATION.name}")
